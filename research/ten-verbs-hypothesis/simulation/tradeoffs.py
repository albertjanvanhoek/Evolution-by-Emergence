"""Trade-offs between verbs, checked properly (answers the outside review, point A).

E2 in run.py correlated each recovered verb with the TRUE setting of every
other verb. The true settings were drawn independently, so near-zero values
there say little. Two better checks:

E2b  Correlation between ESTIMATION ERRORS (recovered minus true, scaled by
     the prior range), from the E1 fits stored in results.json. If one verb
     compensates for another, their errors move together.
E2c  Profile likelihood for Change. For 20 agents in the base condition, hold
     Change at the true value times 0.7, 0.85, 1, 1.15 and 1.3, refit the other
     five belief verbs, and record how the fit worsens and how far the other
     verbs move to compensate.

E2d  Optimiser check (added after a second outside review). E2c measured each
     restricted fit against the fit with Change held at its TRUE value; the
     true value need not maximise the likelihood of a finite noisy dataset,
     so a higher likelihood away from it does not show optimiser failure.
     E2d fits the same 20 agents without restriction, once with 3 random
     starts (as in E1) and once with 20, and compares every restricted fit
     with the best unrestricted one. A restricted fit that beats the best
     unrestricted fit is direct evidence that the optimiser missed the maximum.

Usage: python tradeoffs.py                    (a few minutes; writes results/)
       python tradeoffs.py --optimiser-check  (E2d only; uses tradeoffs.json)
"""

from __future__ import annotations

import json
import os

import numpy as np

from fit import fit_joint
from model import (CONDITIONS, JOINT, LABELS, N, PRIOR, agent_record,
                   draw_params, simulate, test_table)

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
SEED = 2026
FACTORS = [0.7, 0.85, 1.0, 1.15, 1.3]
N_AGENTS = 20


def error_correlations():
    d = json.load(open(os.path.join(RES, "results.json")))["e1_raw"]
    out = {}
    for regime in ["rich", "sparse"]:
        E = [np.concatenate([(np.array(d[c][regime][v]) - np.array(d[c]["true"][v]))
                             / (PRIOR[v][1] - PRIOR[v][0]) for c in d]) for v in JOINT]
        out[regime] = np.corrcoef(E).tolist()
    return out


def profiles():
    rng = np.random.default_rng(SEED)          # same draw as E1, base condition
    pr = draw_params(rng, (20, N))
    cond = CONDITIONS["base"]
    rec = simulate(pr, cond, rng)
    P = test_table(False)
    ic = JOINT.index("change")
    out = {}
    for regime in ["rich", "sparse"]:
        rows = []
        for k in range(N_AGENTS):
            r, n = divmod(k, N)
            a = agent_record(rec, r, n)
            true_c = pr["change"][r, n]
            fr = np.random.default_rng(SEED + 500 + k)
            prof = []
            for f in FACTORS:
                c = float(np.clip(true_c * f, 0.02, 1.0))
                th, ll, _ = fit_joint(a, P, regime, fr, fixed={ic: c})
                prof.append({"factor": f, "change": c, "ll": float(ll),
                             **{v: float(th[i]) for i, v in enumerate(JOINT)}})
            rows.append(prof)
        out[regime] = rows
        print(f"profiles {regime} done", flush=True)
    return out


def summarise(err, prof):
    L = ["# Trade-offs between verbs (generated by tradeoffs.py)", "",
         "## E2b. Correlation between estimation errors (pooled over 7 conditions, 700 agents)", "",
         "Errors are recovered minus true, scaled by the range each verb was drawn from."]
    for regime in ["rich", "sparse"]:
        L += ["", f"### {regime}", "", "| | " + " | ".join(LABELS[v] for v in JOINT) + " |",
              "|---|" + "---|" * len(JOINT)]
        for i, v in enumerate(JOINT):
            L.append(f"| {LABELS[v]} | " + " | ".join(f"{x:.2f}" for x in err[regime][i]) + " |")
    L += ["", "## E2c. Profile likelihood for Change (20 agents, base condition)", "",
          "Change held at the true value times the factor; the other five refitted. "
          "Columns: mean loss in log-likelihood against the factor-1 fit, and the mean "
          "shift of each refitted verb against its factor-1 value (median in brackets).", ""]
    for regime in ["rich", "sparse"]:
        L += [f"### {regime}", "", "| factor | loss in log-lik | " +
              " | ".join(LABELS[v] for v in JOINT if v != "change") + " |",
              "|---|---|" + "---|" * (len(JOINT) - 1)]
        rows = prof[regime]
        for fi, f in enumerate(FACTORS):
            loss = [r[2]["ll"] - r[fi]["ll"] for r in rows]
            cells = []
            for v in JOINT:
                if v == "change":
                    continue
                sh = [r[fi][v] - r[2][v] for r in rows]
                cells.append(f"{np.mean(sh):+.3f} ({np.median(sh):+.3f})")
            L.append(f"| {f} | {np.mean(loss):.1f} ({np.median(loss):.1f}) | " + " | ".join(cells) + " |")
        L.append("")
    with open(os.path.join(RES, "tradeoffs.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


def optimiser_check():
    d = json.load(open(os.path.join(RES, "tradeoffs.json")))
    rng = np.random.default_rng(SEED)
    pr = draw_params(rng, (20, N))
    rec = simulate(pr, CONDITIONS["base"], rng)
    P = test_table(False)
    out = {}
    for regime in ["rich", "sparse"]:
        rows = []
        for k in range(N_AGENTS):
            r, n = divmod(k, N)
            a = agent_record(rec, r, n)
            _, ll3, _ = fit_joint(a, P, regime, np.random.default_rng(SEED + 900 + k), starts=3)
            _, ll20, _ = fit_joint(a, P, regime, np.random.default_rng(SEED + 950 + k), starts=20)
            best_unres = max(ll3, ll20)
            restricted = [p["ll"] for p in d["profiles"][regime][k]]
            rows.append({"ll3": float(ll3), "ll20": float(ll20),
                         "restricted": restricted,
                         "max_restricted_minus_best": float(max(restricted) - best_unres)})
        out[regime] = rows
        print(f"optimiser check {regime} done", flush=True)
    d["optimiser_check"] = out
    with open(os.path.join(RES, "tradeoffs.json"), "w") as fh:
        json.dump(d, fh)
    L = ["", "## E2d. Optimiser check (20 agents, base condition)", "",
         "Unrestricted fits with 3 random starts (as in E1) and with 20. 'Shortfall' is how far",
         "the 3-start fit falls below the better of the two. 'Restricted beats unrestricted'",
         "counts agents for which some fit with Change held fixed (E2c) reached a higher",
         "log-likelihood than the best unrestricted fit, by more than 0.01: direct evidence",
         "that the unrestricted search missed the maximum.", "",
         "| regime | 3-start shortfall: mean (max) | agents with shortfall > 0.5 | restricted beats unrestricted |",
         "|---|---|---|---|"]
    for regime in ["rich", "sparse"]:
        rows = out[regime]
        sf = [max(r["ll3"], r["ll20"]) - r["ll3"] for r in rows]
        beat = sum(r["max_restricted_minus_best"] > 0.01 for r in rows)
        L.append(f"| {regime} | {np.mean(sf):.2f} ({np.max(sf):.2f}) | "
                 f"{sum(x > 0.5 for x in sf)} of {len(rows)} | {beat} of {len(rows)} |")
    with open(os.path.join(RES, "tradeoffs.md"), "a") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    import sys
    if "--optimiser-check" in sys.argv:
        optimiser_check()
        return
    err = error_correlations()
    prof = profiles()
    with open(os.path.join(RES, "tradeoffs.json"), "w") as fh:
        json.dump({"error_correlations": err, "profiles": prof}, fh)
    summarise(err, prof)
    print("written")


if __name__ == "__main__":
    main()
